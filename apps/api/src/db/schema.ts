export const payrollRuns = pgTable(
  'payroll_runs',
  {
    id: id(),
    organizationId: uuid('organization_id')
      .notNull()
      .references(() => organizations.id),
    countryCode: text('country_code')
      .notNull()
      .references(() => countries.code),
    currency: text('currency').notNull(),
    periodYear: integer('period_year').notNull(),
    periodMonth: integer('period_month').notNull(),
    status: payrollRunStatusEnum('status').notNull().default('draft'),
    workerCount: integer('worker_count').notNull().default(0),
    grossMinor: money('gross_minor').notNull().default(0),
    deductionsMinor: money('deductions_minor').notNull().default(0),
    netMinor: money('net_minor').notNull().default(0),
    employerCostMinor: money('employer_cost_minor').notNull().default(0),
    reimbursementsMinor: money('reimbursements_minor').notNull().default(0),
    rejectionReason: text('rejection_reason'),
    createdBy: uuid('created_by').references(() => users.id),
    submittedAt: ts('submitted_at'),
    approvedBy: uuid('approved_by').references(() => users.id),
    approvedAt: ts('approved_at'),
    paidAt: ts('paid_at'),
    createdAt: createdAt(),
  },
  (t) => [
    // One run per org + country + month. Two people clicking "create" at once
    // get one run and one 409, not two payrolls.
    uniqueIndex('payroll_runs_period_unique').on(
      t.organizationId,
      t.countryCode,
      t.periodYear,
      t.periodMonth,
    ),
    check('payroll_runs_month_valid', sql`${t.periodMonth} between 1 and 12`),
  ],
);

