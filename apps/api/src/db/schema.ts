// ---------- reference data (global, not tenant-owned) ----------
export const countries = pgTable('countries', {
  code: text('code').primaryKey(), // ISO 3166-1 alpha-2
  name: text('name').notNull(),
  region: text('region').notNull(),
  currency: text('currency').notNull(), // ISO 4217
  employerContributions: jsonb('employer_contributions')
    .$type<ContributionRule[]>()
    .notNull()
    .default([]),
  employeeDeductions: jsonb('employee_deductions')
    .$type<ContributionRule[]>()
    .notNull()
    .default([]),
  monthlyFeeUsdMinor: money('monthly_fee_usd_minor').notNull().default(59_900),
  annualLeaveDays: integer('annual_leave_days').notNull().default(20),
  noticePeriodDays: integer('notice_period_days').notNull().default(30),
  probationDays: integer('probation_days').notNull().default(90),
  eorSupported: boolean('eor_supported').notNull().default(true),
  requiredDocuments: jsonb('required_documents').$type<DocumentKind[]>().notNull().default([]),
});

/** Units of `currency` per 1 USD. USD itself is stored as 1. */
export const fxRates = pgTable('fx_rates', {
  currency: text('currency').primaryKey(),
  perUsd: numeric('per_usd', { precision: 18, scale: 8 }).notNull(),
  updatedAt: ts('updated_at').notNull().defaultNow(),
});

// ---------- tenancy & identity ----------
export const organizations = pgTable('organizations', {
  id: id(),
  name: text('name').notNull(),
  legalName: text('legal_name').notNull(),
  countryCode: text('country_code')
    .notNull()
    .references(() => countries.code),
  billingEmail: text('billing_email').notNull(),
  createdAt: createdAt(),
});

export const users = pgTable(
  'users',
  {
    id: id(),
    // Stored lower-cased (the zod schema normalises it), so a plain unique index is enough.
    email: text('email').notNull(),
    passwordHash: text('password_hash').notNull(),
    fullName: text('full_name').notNull(),
    role: userRoleEnum('role').notNull(),
    /** Null only for platform admins (Meridian staff), who belong to no client. */
    organizationId: uuid('organization_id').references(() => organizations.id),
    isActive: boolean('is_active').notNull().default(true),
    createdAt: createdAt(),
  },
  (t) => [
    uniqueIndex('users_email_unique').on(t.email),
    index('users_org_idx').on(t.organizationId),
    check(
      'users_org_matches_role',
      sql`(${t.role} = 'platform_admin') = (${t.organizationId} is null)`,
    ),
  ],
);

export const sessions = pgTable(
  'sessions',
  {
    id: id(),
    /** SHA-256 of the cookie value. A stolen database dump cannot be replayed as cookies. */
    tokenHash: text('token_hash').notNull(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    expiresAt: ts('expires_at').notNull(),
    userAgent: text('user_agent'),
    createdAt: createdAt(),
  },
  (t) => [
    uniqueIndex('sessions_token_hash_unique').on(t.tokenHash),
    index('sessions_user_idx').on(t.userId),
  ],
);

// ---------- workers ----------
export const workers = pgTable(
  'workers',
  {
    id: id(),
    organizationId: uuid('organization_id')
      .notNull()
      .references(() => organizations.id),
    /** The portal login for this worker, once they accept their invite. */
    userId: uuid('user_id').references(() => users.id),
    type: workerTypeEnum('type').notNull(),
    status: workerStatusEnum('status').notNull().default('onboarding'),
    firstName: text('first_name').notNull(),
    lastName: text('last_name').notNull(),
    email: text('email').notNull(),
    countryCode: text('country_code')
      .notNull()
      .references(() => countries.code),
    jobTitle: text('job_title').notNull(),
    department: text('department'),
    startDate: date('start_date').notNull(),
    endDate: date('end_date'),
    salaryMinor: money('salary_minor').notNull(),
    payBasis: payBasisEnum('pay_basis').notNull(),
    /** Copied from the country at hire time; a worker's pay currency never changes silently. */
    currency: text('currency').notNull(),
    createdAt: createdAt(),
  },
  (t) => [
    uniqueIndex('workers_org_email_unique').on(t.organizationId, t.email),
    uniqueIndex('workers_user_unique').on(t.userId),
    index('workers_org_status_idx').on(t.organizationId, t.status),
    check('workers_salary_positive', sql`${t.salaryMinor} > 0`),
    check('workers_dates_ordered', sql`${t.endDate} is null or ${t.endDate} >= ${t.startDate}`),
  ],
);

