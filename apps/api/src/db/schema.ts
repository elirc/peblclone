/**
 * The whole database, in one file, on purpose.
 *
 * Conventions:
 *  - Primary keys are random UUIDs generated by Postgres (no sequential ids to guess).
 *  - EVERY tenant-owned table carries `organization_id`. It is redundant on child
 *    tables (a payroll item could reach its org through its run), but it lets
 *    every query filter by tenant directly, which makes "forgot the tenant
 *    check" bugs much harder to write. See ADR 0002.
 *  - Money is `bigint` minor units + a currency column. Never float/numeric.
 *  - `timestamptz` for instants, `date` for calendar days.
 *  - Deleting a parent RESTRICTs by default: payroll history must not vanish
 *    because somebody deleted a worker. Only pure child rows CASCADE.
 */

const id = () => uuid('id').primaryKey().defaultRandom();
const createdAt = () => timestamp('created_at', { withTimezone: true }).notNull().defaultNow();
const ts = (name: string) => timestamp(name, { withTimezone: true });
const money = (name: string) => bigint(name, { mode: 'number' });

