// ---------- contracts ----------
export const contracts = pgTable(
  'contracts',
  {
    id: id(),
    organizationId: uuid('organization_id')
      .notNull()
      .references(() => organizations.id),
    workerId: uuid('worker_id')
      .notNull()
      .references(() => workers.id),
    status: contractStatusEnum('status').notNull().default('draft'),
    title: text('title').notNull(),
    body: text('body').notNull(),
    terms: jsonb('terms').$type<ContractTerms>().notNull(),
    sentAt: ts('sent_at'),
    signedAt: ts('signed_at'),
    signedByName: text('signed_by_name'),
    signedByUserId: uuid('signed_by_user_id').references(() => users.id),
    signatureIp: text('signature_ip'),
    activatedAt: ts('activated_at'),
    terminatedAt: ts('terminated_at'),
    createdBy: uuid('created_by').references(() => users.id),
    createdAt: createdAt(),
  },
  (t) => [
    index('contracts_org_idx').on(t.organizationId),
    index('contracts_worker_idx').on(t.workerId),
    // At most one "live" contract per worker. A partial unique index enforces
    // in the database what an if-statement can only enforce without concurrency.
    uniqueIndex('contracts_one_live_per_worker')
      .on(t.workerId)
      .where(sql`${t.status} in ('draft', 'sent', 'signed', 'active')`),
  ],
);

